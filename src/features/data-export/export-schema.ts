export const exportResponseSchema = z.strictObject({
  format: z.literal("ledgerly-backup"),
  version: z.literal(1),
  exported_at: z.iso.datetime({ offset: true }),
  app: z.strictObject({ name: z.literal("Ledgerly") }),
  data: dataSchema,
  record_counts: z.record(z.enum(exportTables as [ExportTable, ...ExportTable[]]), z.number().int().nonnegative()),
}).superRefine((value, context) => {
  for (const table of exportTables) {
    if (value.data[table].length !== value.record_counts[table]) {
      context.addIssue({ code: "custom", message: "Incomplete export." })
    }
  }
})
export type ExportResponse = z.infer<typeof exportResponseSchema>
